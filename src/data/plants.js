// ─── FILTER ─────────────────────────────────────────────────────────────────
export function filterPlants({ licht, wasser, boden, types, wuchsform, drainage, ph, searchTerm } = {}) {
  return PLANTS.filter(p => {
    if (licht && !p.licht.includes(licht)) return false
    if (wasser && !p.wasser.includes(wasser)) return false
    if (boden && !p.boden.includes(boden)) return false
    if (types && types.length && !types.includes(p.type)) return false
    if (wuchsform && p.wuchsform !== wuchsform) return false
    if (drainage && p.drainage !== drainage) return false
    if (ph && (p.ph_min > ph || p.ph_max < ph)) return false
    if (searchTerm) {
      const s = searchTerm.toLowerCase()
      if (!p.name.toLowerCase().includes(s) && !p.latin.toLowerCase().includes(s) &&
          !p.beschreibung?.toLowerCase().includes(s)) return false
    }
    return true
  })
}
