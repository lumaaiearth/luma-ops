// Hilfsfunktionen
export const LICHT_LABELS = { 1: 'Sonnig', 2: 'Halbschatten', 3: 'Schatten' }
export const WASSER_LABELS = { 1: 'Trocken', 2: 'Mäßig feucht', 3: 'Feucht' }
export const BODEN_LABELS = { sandy: 'Sandig', loamy: 'Lehmig', clay: 'Tonig', humus: 'Humusreich' }
export const TYPE_LABELS = { staude: 'Staude', strauch: 'Strauch', gras: 'Gras', einjährig: 'Einjährig', zweijährig: 'Zweijährig' }

export const MONTHS = ['Jan','Feb','Mär','Apr','Mai','Jun','Jul','Aug','Sep','Okt','Nov','Dez']

export function filterPlants({ licht, wasser, boden, types, searchTerm }) {
  return PLANTS.filter(p => {
    if (licht && !p.licht.includes(licht)) return false
    if (wasser && !p.wasser.includes(wasser)) return false
    if (boden && !p.boden.includes(boden)) return false
    if (types && types.length && !types.includes(p.type)) return false
    if (searchTerm) {
      const s = searchTerm.toLowerCase()
      if (!p.name.toLowerCase().includes(s) && !p.latin.toLowerCase().includes(s)) return false
    }
    return true
  })
}
